def now_local() -> datetime:
    return datetime.now(TZ)


def welcome_info(user) -> dict:
    now = now_local()
    today = now.date()
    h = now.hour
    greeting = "صباح الخير" if 4 <= h < 12 else "مساء الخير"
    name = (getattr(user, "display_name", "") or "").split()
    first = name[0] if name else ""
    sunday = today - timedelta(days=(today.weekday() + 1) % 7)  # بداية أسبوع العمل (الأحد)
    days = []
    for i, (wd, label) in enumerate(WORK_DAYS):
        d = sunday + timedelta(days=i)
        state = "today" if d == today else ("past" if d < today else "next")
        days.append(dict(label=label, date=d, state=state))
    weekend = today.weekday() in (4, 5)  # الجمعة والسبت
    return dict(greeting=greeting, first=first, phrase=PHRASES[today.toordinal() % len(PHRASES)],
                greg=f"{today.day} {MONTHS[today.month - 1]} {today.year}", iso=today.isoformat(),
                days=days, weekend=weekend)
